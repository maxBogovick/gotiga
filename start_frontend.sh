#!/bin/bash
# Скрипт для запуска веб-фронтенда (SvelteKit)

echo "=========================================="
echo "🎨 Запуск веб-фронтенда (SvelteKit/Vite)..."
echo "=========================================="

# Переходим в корень проекта, где находится package.json
cd "$(dirname "$0")" || exit

# Устанавливаем зависимости, если их нет (опционально)
if [ ! -d "node_modules" ]; then
    echo "Установка npm зависимостей..."
    npm install
fi

# Запускаем фронтенд
npm run dev
