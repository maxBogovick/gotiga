-- Второй способ начать матч — обещанная половина `battle_decks`.
--
-- Одна колонка, а не второй путь создания партии. При `'deck'` сторона гостя
-- собирается из его стола, сторона хранителя — из `setup`, как была; всё
-- остальное переиспользуется без правки: та же полка испытаний, та же запись
-- матча, тот же снимок в момент начала, то же правило «пыль однажды».
--
-- Если бы для этого понадобилось править `reduce`, журнал или форму записи —
-- ветка была бы сделана неверно.
--
--   'scripted' — обе стороны заданы рукой. Этюд: у него есть решение.
--   'deck'     — хранитель ставит своё, гость приводит свой стол. Встреча.
--
-- Умолчание `'scripted'` — чтобы уже выложенные этюды не поменяли смысл от
-- миграции.
ALTER TABLE battle_challenges
    ADD COLUMN IF NOT EXISTS player_side TEXT NOT NULL DEFAULT 'scripted'
        CHECK (player_side IN ('scripted', 'deck'));
