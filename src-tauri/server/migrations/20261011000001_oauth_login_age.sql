-- Самоподтверждение «мне 16 или больше» для имён, заводимых через Google и Apple.
--
-- Политика требует его на каждой форме, где собираются контакты, а у этой двери
-- формы нет: человек уходит к провайдеру и возвращается уже с именем. Поэтому
-- отметка едет вместе с попыткой входа, и проверяет её сервер в тот единственный
-- миг, когда заводится НОВОЕ имя. Вернувшегося, привязку из профиля и слияние с
-- именем по подтверждённой почте она не касается — нового человека там нет.
--
-- Проверка на сервере, а не только на странице: иначе её обходил бы любой
-- запрос к API без галочки.
ALTER TABLE oauth_logins ADD COLUMN IF NOT EXISTS age_confirmed BOOLEAN NOT NULL DEFAULT FALSE;

