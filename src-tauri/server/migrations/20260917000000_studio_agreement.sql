-- Соглашение автора.
--
-- Принимается один раз, перед первой выкладкой на люди, и записывается ДАТОЙ И
-- ВЕРСИЕЙ, а не галочкой «да».
--
-- Галочка отвечает на вопрос «согласен ли», а спрашивать через год придётся
-- другое: «с чем именно он согласился». Текст соглашения меняется — в него
-- дописывают то, чего не предусмотрели, — и человек, принявший прошлую
-- редакцию, не принимал новую. Дата без версии этого не расскажет, версия без
-- даты не скажет когда, а вместе они отвечают на оба вопроса без архива
-- согласий.
--
-- Живёт на `users`, а не отдельной таблицей: согласие у человека одно, и второй
-- строки для него не бывает. Отдельная таблица понадобится в тот день, когда
-- согласий станет несколько (например, отдельное на продажу), и тогда это будет
-- переезд одного столбца, а не разбор истории.
ALTER TABLE users ADD COLUMN IF NOT EXISTS studio_agreed_at TIMESTAMPTZ;
ALTER TABLE users ADD COLUMN IF NOT EXISTS studio_agreement TEXT;
