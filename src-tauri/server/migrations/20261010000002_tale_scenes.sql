-- Сцена байки, которую правит автор на столе рассказов (`TaleSceneEditor`):
-- кадры, тип каждого перехода и момент, когда он идёт.
--
-- Отдельная таблица, а не колонка листа: лист несёт текст и обвязку выхода
-- (письма, канал, порядок полки), а сцена — подача, и автосохранение листа её
-- не должно ни трогать, ни терять. Как у `sequel_of`, у сцены своя ручка.
--
-- `data` — JSON одной формы (`TaleScene` в models), и сервер сам приводит его в
-- порядок при записи (`normalize_tale_scene`): браузер пишет, а страница
-- читателя потом доверяет тому, что лежит, — типы переходов и адреса кадров
-- проверены один раз здесь, а не при каждом показе.
--
-- `created_at` не меняется при правках: по нему отчёт опыта «со сценой / без»
-- не считает визиты, бывшие до того, как у байки появилась сцена.
CREATE TABLE IF NOT EXISTS tale_scenes (
    tale_id    UUID PRIMARY KEY REFERENCES gazette_leaves(id) ON DELETE CASCADE,
    data       JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
