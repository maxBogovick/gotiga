-- Вход через Telegram: вторая дверь в тот же архив.
--
-- Узнают вернувшегося по ЧИСЛУ (`telegram_id`), а не по имени: `@username`
-- человек меняет свободно, освобождённое имя забирает кто угодно, и поиск по
-- нему однажды отдал бы чужой архив. Число за аккаунтом закреплено навсегда.
--
-- `telegram_username` хранится только для того, чтобы напечатать «Telegram:
-- @маша» в профиле, и переписывается при каждом входе. Имя в профиле при этом
-- НЕ трогается после создания аккаунта: человек мог назвать себя на сайте
-- иначе, и второй вход, вернувший телеграмовское имя, молча испортил бы его
-- выбор. Фотография не берётся вовсе — её адрес ведёт на серверы Telegram,
-- протухает и утекает в `img-src`; аватар в доме свой, загружаемый.
ALTER TABLE users ADD COLUMN IF NOT EXISTS telegram_id        BIGINT;
ALTER TABLE users ADD COLUMN IF NOT EXISTS telegram_username  TEXT;
ALTER TABLE users ADD COLUMN IF NOT EXISTS telegram_linked_at TIMESTAMPTZ;

CREATE UNIQUE INDEX IF NOT EXISTS users_telegram_id_idx ON users (telegram_id)
    WHERE telegram_id IS NOT NULL;

-- Почта перестаёт быть условием существования аккаунта.
--
-- Telegram не отдаёт почту НИКОГДА — ни виджет, ни Mini App. Спрашивать её на
-- третьем касании входа значит терять человека ровно там, ради чего вход и
-- облегчали. Почта нужна ДЕЛУ, а не двери: бронь, заказ и лист ожидания уже
-- принимают её в самом запросе и обращаются к аккаунту только как к запасному
-- варианту (`services/mod.rs`, `user_email.unwrap_or("")`). Там её и спросят —
-- там, где без обратного адреса дом физически не сможет ответить.
--
-- Пустая строка вместо NULL не годится: второй такой аккаунт упёрся бы в
-- уникальный индекс. NULL-ов Postgres пропускает сколько угодно, поэтому
-- `idx_users_email` остаётся как был.
ALTER TABLE users ALTER COLUMN email DROP NOT NULL;

-- Значки перестают быть условием существования аккаунта.
--
-- У вошедшего Телеграмом визуального пароля нет, и `login_verify` отвечает
-- такому аккаунту обычным Unauthorized — тем же, что и неизвестной почте
-- (декой-набор рисуется и для неё, перечисление аккаунтов по-прежнему
-- невозможно). Назначить себе значки человек сможет позже через `/set-password`,
-- когда у аккаунта появится почта.
ALTER TABLE users ALTER COLUMN visual_password_hash DROP NOT NULL;
