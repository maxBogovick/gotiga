-- Три вещи, которых не хватало полке этюдов: свои правила у испытания, память
-- о том, КАК партия была пройдена, и планка «лучшее известное».

-- ── Правила партии ──────────────────────────────────────────────────────────
--
-- До сих пор все этюды игрались по умолчаниям дома: `MatchState::begin` брал
-- `Rules::default()`, и ни одна из измеренных ручек — шаг тратит ход, сдача,
-- потолок действий, штраф в упор — этюду доступна не была. Полка была списком
-- расстановок; с этой колонкой она становится списком разных игр.
--
-- Правила испытания живут в его `setup` (это JSON, миграции не требуется), а
-- ЗДЕСЬ лежит их снимок на момент начала партии — по той же причине, по которой
-- рядом лежит снимок тел: правка испытания не должна переписывать сыгранное.
--
-- NULL — «дом», и это ровно то, под чем игрались все прежние партии. Поэтому
-- пересмотр старой записи не меняется от этой миграции ни на бит.
ALTER TABLE battle_matches
    ADD COLUMN IF NOT EXISTS rules TEXT CHECK (rules IS NULL OR char_length(rules) <= 2000);

-- ── Как пройдено ────────────────────────────────────────────────────────────
--
-- Победа была двоичной: выиграл или нет. Пыль за этюд платится однажды, и
-- пройденный этюд не давал ни одной причины к нему вернуться.
--
-- Эти два числа — причина. Сколько дел сделал гость (конец хода делом не
-- считается: это не выбор, а его отсутствие) и скольких тел недосчитался.
-- Оба считаются свёрткой журнала в момент исхода, а не копятся по ходу: журнал
-- и есть истина, а счётчик, который ведут параллельно, однажды с ней разойдётся.
ALTER TABLE battle_matches
    ADD COLUMN IF NOT EXISTS player_acts SMALLINT CHECK (player_acts IS NULL OR player_acts >= 0);
ALTER TABLE battle_matches
    ADD COLUMN IF NOT EXISTS bodies_lost SMALLINT CHECK (bodies_lost IS NULL OR bodies_lost >= 0);

-- Планка этюда — не вычисленный дома оптимум, а лучшая линия, которую кто-либо
-- прошёл. Она поднимается сама, живой рукой, и её незачем считать перебором:
-- у этой доски ветвление широкое, честный перебор до конца не доходит, а
-- печать «лучшее известное» не обещает того, чего дом не знает.
--
-- Индекс частичный: планку меряют только выигранные партии.
CREATE INDEX IF NOT EXISTS battle_matches_line_idx
    ON battle_matches (challenge_id, player_acts)
    WHERE outcome = 'player' AND player_acts IS NOT NULL;
