-- Владение картами: покупка, пометка «новая», цена ступеней уровня.
--
-- Книга кошелька и таблица владения заведены раньше (20260825000000) и всё это
-- время стояли пустыми: пыль капала за этюды, а потратить её было не на что.
-- Здесь достраивается только то, чего им не хватало.

-- Цена ступеней уровня — четыре числа: 1→2, 2→3, 3→4, 4→5.
--
-- Массивом, а не восемью колонками, и только в пыли. Пыль — это время
-- (`TASKS-BATTLES.md` §0.1), и повышение уровня своего экземпляра как раз
-- покупается временем; корм даётся хранителем за поступок, и ступени за него
-- превратили бы именной подарок в расходник.
--
-- Заводится сейчас, работать начнёт в 1c: живую таблицу с чужими покупками
-- мигрировать дороже, чем пустую колонку подождать.
ALTER TABLE battle_cards
    ADD COLUMN IF NOT EXISTS level_price_dust INTEGER[];

ALTER TABLE battle_cards
    DROP CONSTRAINT IF EXISTS battle_cards_level_prices_ck;
ALTER TABLE battle_cards
    ADD CONSTRAINT battle_cards_level_prices_ck CHECK (
        level_price_dust IS NULL
        OR (
            array_length(level_price_dust, 1) = 4
            -- Поимённо, а не `unnest`: в CHECK нельзя подзапрос, а ступеней
            -- ровно четыре и больше не станет — уровней всего пять.
            AND level_price_dust[1] >= 0
            AND level_price_dust[2] >= 0
            AND level_price_dust[3] >= 0
            AND level_price_dust[4] >= 0
        )
    );

-- Что покупка списывает: строка со знаком минус в книге и строка владения,
-- обе в одной транзакции. Ключ идемпотентности у покупки свой и говорящий:
-- `buy:{card_id}` — карту нельзя купить дважды, и повтор запроса не спишет
-- второй раз даже при двойном щелчке.
--
-- Отдельной таблицы покупок нет и не нужно: книга уже летопись.

-- Ставки начисления за внимание живут в `settings` (ключ `battle_dust_rates`),
-- рядом с рамками чинов, — это настройка хранителя, а не схема.
