-- Укрепление входа: подтверждённая почта, отпечатки вместо ключей, счёт
-- неудач по паре «почта и сеть».
--
-- Три вещи, которые до сих пор были устроены на доверии:
--
-- 1. Почта не подтверждалась НИГДЕ — ни при заведении имени, ни когда её
--    называло дело. При этом «забыли знаки» делает её каналом полного
--    восстановления: по письму назначаются новые знаки и гасятся все сессии.
--    То есть опечатка в адресе отдавала имя постороннему, а занять чужой
--    адрес можно было, просто набрав его.
--
-- 2. И ключ сессии, и ключ сброса лежали в базе открытым текстом. Чтение базы
--    (дамп, бэкап, глаз через плечо у `psql`) — это сразу вход в каждое имя на
--    месяц вперёд, без единого пароля.
--
-- 3. Неудачи считались по одной почте. Пять неверных попыток по известному
--    адресу запирали человека на пятнадцать минут, и повторить это мог кто
--    угодно сколько угодно раз.

-- ── 1. Почта подтверждается ──────────────────────────────────────────────
--
-- `email_confirmed_at` — отметка «мы дозвонились до этого ящика, и человек
-- открыл дверь изнутри». До неё адрес годится, чтобы дом ОТВЕТИЛ на заказ, но
-- не годится, чтобы дом ВПУСТИЛ: сброс знаков и привязка гостевых расписок
-- спрашивают именно её.
--
-- Хранится отпечаток письма, а не само слово (`email_confirm_hash` —
-- SHA-256): ссылка живёт в почтовом ящике и в адресной строке, и база не
-- обязана хранить её второй раз.
ALTER TABLE users ADD COLUMN IF NOT EXISTS email_confirmed_at       TIMESTAMPTZ;
ALTER TABLE users ADD COLUMN IF NOT EXISTS email_confirm_hash       TEXT;
ALTER TABLE users ADD COLUMN IF NOT EXISTS email_confirm_expires_at TIMESTAMPTZ;

CREATE UNIQUE INDEX IF NOT EXISTS idx_users_email_confirm_hash
    ON users (email_confirm_hash) WHERE email_confirm_hash IS NOT NULL;

-- Уже живущие имена считаются подтверждёнными. Задним числом отнять у них
-- канал восстановления значило бы запереть снаружи всех разом — за дыру,
-- которую оставил дом, а не они.
UPDATE users SET email_confirmed_at = created_at
 WHERE email IS NOT NULL AND email_confirmed_at IS NULL;

-- ── 2. В базе лежит отпечаток, а не ключ ─────────────────────────────────
--
-- Колонки те же (`user_sessions.token`, `users.password_reset_token`), но
-- отныне в них SHA-256 от выданного ключа. Сравнение идёт по отпечатку,
-- поэтому сам ключ базе не нужен вовсе.
--
-- Старые строки не переводятся — из отпечатка ключ не восстановить. Они
-- гасятся: это один общий выход из дома, после которого каждый входит заново.
-- Оставить их значило бы оставить открытым ровно то, что закрывается.
TRUNCATE TABLE user_sessions;
UPDATE users SET password_reset_token = NULL, password_reset_expires_at = NULL
 WHERE password_reset_token IS NOT NULL;

-- ── 3. Неудачи считаются по паре ─────────────────────────────────────────
--
-- Счёт идёт и по почте, и по сети, и запирает только их сочетание, поэтому
-- чужой не запирает хозяина. Обе выборки ходят по времени — индекс общий.
CREATE INDEX IF NOT EXISTS idx_login_attempts_email_time
    ON login_attempts (email, attempted_at DESC);
CREATE INDEX IF NOT EXISTS idx_login_attempts_ip_time
    ON login_attempts (ip, attempted_at DESC);
