-- Этюд платит и за доведённое до конца, а не только за победу.
--
-- До сих пор новичок, проигравший хранителю первую партию, не получал ровно
-- ничего. Это худший из возможных ответов на первую же попытку сыграть: человек
-- сел за доску, дошёл до исхода — и комната промолчала.
--
-- Отдельным числом, а не долей от победы: доля пряталась бы в коде, а хранителю
-- надо видеть оба числа рядом и решать самому. Ключ у него свой
-- (`battle:{id}:finish`), поэтому защита от фермы прежняя — по одному ключу на
-- этюд, сколько бы раз его ни переигрывали.
ALTER TABLE battle_challenges
    ADD COLUMN IF NOT EXISTS reward_finish_dust INTEGER NOT NULL DEFAULT 0;

-- Уже стоящим этюдам — пятая часть от победы, но не меньше одной пыли там, где
-- за победу вообще платят. Пятая, а не половина: дойти до конца легче, чем
-- выиграть, и платить за это вровень значит обесценить победу. Число это
-- хранитель поправит на своём столе; миграция лишь не оставляет их с нулём.
UPDATE battle_challenges
   SET reward_finish_dust = GREATEST(1, ROUND(reward_dust / 5.0)::int)
 WHERE reward_dust > 0 AND reward_finish_dust = 0;
