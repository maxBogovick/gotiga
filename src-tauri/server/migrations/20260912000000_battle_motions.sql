-- Движения боя: чем карта показывает свой удар, чару, выстрел и лечение.
--
-- Сам свод движений живёт не здесь, а в `settings.battle_motions` — ровно там
-- же, где рамки чинов, и по той же причине: это словарь дома, один на всю
-- комнату, а не вещь, принадлежащая строке. Здесь заводится только то, чем
-- строка на этот словарь ССЫЛАЕТСЯ.
--
-- Ссылка, а не само движение. Двенадцать стрелков обязаны стрелять одинаково, и
-- поправка к стреле должна быть одной правкой, а не двенадцатью. Поэтому карта
-- НАДЕВАЕТ движение из ящика — тем же жестом, каким надевает наряд.

-- Что эта карта показывает на каждом поводе. JSON
-- `{blow?, spell?, mend?, arrive?, fall?, unseen?}` — id движений из свода.
-- `NULL` (и любой не названный повод) — умолчание дома, то есть ровно то, что
-- комната делала до движка.
ALTER TABLE battle_cards ADD COLUMN IF NOT EXISTS motion_wear TEXT;

-- То же у расы, и стоит между картой и домом: все лучники расы стреляют её
-- стрелой, пока отдельная карта не скажет иначе. Цепочка та же, что у наряда
-- (карта → уровень расы → чин → дом), потому что вторую цепочку хранителю
-- пришлось бы держать в голове отдельно.
ALTER TABLE battle_races ADD COLUMN IF NOT EXISTS motion_wear TEXT;

-- Седьмое слово роли на складе деталей.
--
-- Роль — это слово, которым хранитель ищет, а не то, что смотрит игра
-- (см. `20260905000000_battle_assets.sql`). Стрела могла бы лежать под
-- `accent` или `other` — и терялась бы среди накладок рам. Слово заводится
-- ровно затем, чтобы ящик, открытый из движения, открывался уже отобранным.
ALTER TABLE battle_assets DROP CONSTRAINT IF EXISTS battle_assets_role_check;
ALTER TABLE battle_assets ADD CONSTRAINT battle_assets_role_check
    CHECK (role IN ('corner', 'sideH', 'sideV', 'accent', 'art', 'motion', 'other'));
