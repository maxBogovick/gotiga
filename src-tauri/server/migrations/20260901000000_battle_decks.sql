-- Стол гостя и заём дома.
--
-- Обещание из `20260829000000_battle_matches.sql` («собственные колоды придут
-- этапом позже и лягут рядом: `battle_decks` и второй способ начать матч»).
-- Здесь первая половина: сама колода. Второй способ начать матч — следующей
-- миграцией, вместе с `player_side` в испытаниях.
--
-- Форма колоды не выбрана вкусом. `TASKS-BATTLE-ENGINE.md` §13.1: правило
-- первого хода (`opening_attacks: 1`, `second_side_coin: 2`) измерено на
-- расстановке «три стоят, три в руке» — «примерно то, что остаётся от колоды из
-- шести после расстановки». Колода другой глубины делает выбранное правило
-- непроверенным.

-- Стол гостя: шесть карт, три на клетках и три в руке.
--
-- Ключ — САМ ГОСТЬ. Одна колода на человека тогда не правило, за которым надо
-- следить, а форма таблицы. Имени у стола нет: он один, и называть его незачем.
-- Если собрание однажды вырастет настолько, что колод понадобится несколько, —
-- это добавленный столбец, а не миграция по живому владению.
--
-- Расхождение с `TASKS-BATTLE-ENGINE.md` §10.4 сознательное. Там у колоды были
-- `id`, `name` и `card_ids UUID[]`, где «порядок = расстановка». Порядок
-- расстановкой быть не может: расстановка — это выбор клеток на своей половине
-- 3×6, и «первая карта = левая дальняя клетка» пришлось бы держать в голове
-- игрока. Клетки пишутся клетками.
--
-- Карты по ИДЕНТИФИКАТОРАМ, а не по слагам, как в испытаниях: испытание —
-- шаблон хранителя, и правка карты должна менять его вместе со всеми; колода —
-- владение, а владение записано на `battle_owned_cards.card_id`.
CREATE TABLE IF NOT EXISTS battle_decks (
    user_id    UUID PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    -- {"board":[{"card":"…","x":1,"y":5},…], "hand":["…","…","…"]}
    --
    -- Состав НЕ проверяется схемой, и это не небрежность. Карту могли снять с
    -- полки после того, как стол был сохранён; стол, ставший незаконным не по
    -- вине гостя, должен открываться, а не отказывать. Законность — вопрос
    -- момента начала партии, и там она и проверяется.
    layout     TEXT NOT NULL CHECK (char_length(layout) <= 4000),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Что дом готов одолжить тому, у кого своего ещё нет.
--
-- Без этого стол — запертая дверь ровно для того, кому комната нужнее всего:
-- новый гость владеет нулём карт, а партия просит шести. Замок откладывает игру
-- до собранной коллекции, а игра — единственная причина коллекцию собирать.
--
-- Отметка на самой карте, а не отдельный список: иначе появляется вторая
-- таблица карт, которую надо держать в согласии с первой.
ALTER TABLE battle_cards
    ADD COLUMN IF NOT EXISTS lendable BOOLEAN NOT NULL DEFAULT FALSE;

-- Пул заёма читается на каждое открытие стола, всегда в одном порядке.
-- Чин здесь не в CHECK, а в отборе: хранитель волен отметить карту заёмной
-- заранее, до того как решит её чин.
CREATE INDEX IF NOT EXISTS battle_cards_lendable_idx
    ON battle_cards (shelf_order NULLS LAST, created_at DESC)
    WHERE lendable AND status = 'published';
