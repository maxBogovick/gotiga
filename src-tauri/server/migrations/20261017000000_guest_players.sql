-- Гость боя: имя без почты и без дверей, заведённое одним нажатием «Начать бой».
--
-- Нужен затем, что партия принадлежит имени (`battle_matches.user_id`), а первый
-- бой обучения должен доигрываться до конца без формы входа. Гостевое имя —
-- обычная строка `users` с отметкой: второй таблицы владения партиями не
-- заводим, иначе она разошлась бы с первой на первой же правке.
--
-- Чем гость ограничен, держит код, а не эта таблица: сессия гостя годится
-- только ручкам боя (`get_player_session_user`), все прочие ручки её не
-- принимают (`get_session_user` отбрасывает гостей), пыль гостю не платится, а
-- встречи со своей колодой ему закрыты.
ALTER TABLE users ADD COLUMN IF NOT EXISTS is_guest BOOLEAN NOT NULL DEFAULT false;

-- Суточная уборка стирает гостей по возрасту имени (сессия живёт 30 дней).
CREATE INDEX IF NOT EXISTS users_guest_created_idx ON users (created_at) WHERE is_guest;
