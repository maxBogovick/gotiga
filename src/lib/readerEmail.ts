import { authStore } from '$lib/stores/auth.svelte';
import { visitorBook } from '$lib/stores/visitor-book.svelte';

/**
 * Адрес, который читатель уже дал сайту: книга дома, а без неё — почта в
 * имени. Пусто — адреса нет, и просьбу о письме придётся задать словами.
 *
 * Один ответ на вопрос «куда писать этому читателю» для всех мест, где его
 * задают (слежка за эскизом, просьба о продолжении, голос «о ком следующая»):
 * написанный в каждом по-своему, он уже разошёлся — одно место начинало с
 * книги, другое с имени, третье считало известным вписанного без адреса.
 *
 * Читает `$state` обоих хранилищ, поэтому внутри `$derived` отвечает сам,
 * когда читатель вписался или вошёл.
 */
export function knownReaderEmail(): string {
  const book = visitorBook.signed ? visitorBook.email.trim() : '';
  return book || authStore.user?.email?.trim() || '';
}
