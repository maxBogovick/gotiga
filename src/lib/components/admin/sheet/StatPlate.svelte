<script lang="ts">
  // Нижняя плашка: числа тела в один ряд, тёмным по светлому листу.
  //
  // Здоровье, сила, броня и шаг стояли девятью полями с подписями капсом —
  // тем же, чем подписан любой другой блок формы. Но эти девять чисел
  // читаются не по одному, а вместе: вопрос к ним всегда «крепкая ли карта»,
  // а не «сколько у неё брони». Плашка отвечает на него одной строкой.
  //
  // Сетка, а не ряд с полосками между ячейками. Полоска, нарисованная у
  // соседа слева, честна ровно до переноса: у первой ячейки второй строки
  // она висит с краю в пустоте, а между строками не появляется вовсе. Здесь
  // полоски и нет — есть просвет в пиксель, сквозь который видно подложку
  // плашки, и он одинаково работает и по вертикали, и по горизонтали.
  import type { Snippet } from 'svelte';

  let { children } = $props<{ children: Snippet }>();
</script>

<div class="plate">
  {@render children()}
</div>

<style>
  .plate {
    /* `auto-fit`, а не `auto-fill`: пустые дорожки схлопываются, и девять
       ячеек становятся девятью колонками, а не семью с обрубком во второй
       строке. Ужимается плашка переносом, когда лист правда узок. */
    display: grid;
    grid-template-columns: repeat(auto-fit, minmax(5.2rem, 1fr));
    gap: 1px;
    padding: 1px;
    /* Чернила, осветлённые ровно настолько, чтобы просвет читался линией и
       не резал: светлая полоса между тёмными ячейками рвёт плашку надвое. */
    background: #4a3b30;
  }
</style>
