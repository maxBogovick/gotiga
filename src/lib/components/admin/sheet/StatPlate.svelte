<script lang="ts">
  // Нижняя плашка: числа тела в один ряд, тёмным по светлому листу.
  //
  // Здоровье, сила, броня и шаг стояли девятью полями с подписями капсом —
  // тем же, чем подписан любой другой блок формы. Но эти девять чисел
  // читаются не по одному, а вместе: вопрос к ним всегда «крепкая ли карта»,
  // а не «сколько у неё брони». Плашка отвечает на него одной строкой.
  //
  // Сетка, а не ряд с полосками между ячейками. Полоска, нарисованная у
  // соседа слева, честна ровно до переноса: у первой ячейки второй строки
  // она висит с краю в пустоте, а между строками не появляется вовсе. Здесь
  // полоски и нет — есть просвет в пиксель, сквозь который видно подложку
  // плашки, и он одинаково работает и по вертикали, и по горизонтали.
  import type { Snippet } from 'svelte';

  let { children, min = '5.2rem' } = $props<{
    children: Snippet;
    /** Ширина, с которой ячейка начинает: дальше она растёт сама. У чисел
     *  умения подписи длиннее — «перезарядка», «звеньев / клеток», — и от
     *  пяти рем они переносились в третью строку. */
    min?: string;
  }>();
</script>

<div class="plate" style="--min:{min}">
  {@render children()}
</div>

<style>
  .plate {
    /* Строкой с переносом, а не сеткой из колонок.
       Сетка казалась правильной, пока я считал ширину по бумаге: девять ячеек
       и девять колонок. На живом столе плашке досталось шестьсот пятнадцать
       пикселей, колонок влезло семь, и во второй строке остались две ячейки и
       ТЁМНАЯ ДЫРКА на пять — потому что `auto-fit` схлопывает дорожку, пустую
       во всех строках, а не в одной. Гибкая строка не знает колонок вовсе:
       ячейки последнего ряда растягиваются и добирают остаток сами. */
    display: flex;
    flex-wrap: wrap;
    gap: 1px;
    padding: 1px;
    /* Чернила, осветлённые ровно настолько, чтобы просвет читался линией и
       не резал: светлая полоса между тёмными ячейками рвёт плашку надвое. */
    background: #4a3b30;
  }
</style>
