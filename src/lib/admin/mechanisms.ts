/**
 * Все механизмы сайта в одном месте: что работает само, чем пользуетесь вы, какие скрипты лежат
 * на компьютере, что просить у Claude. Читает вкладка «Механизмы».
 *
 * Новый механизм не считается готовым, пока его нет здесь (правило в CLAUDE.md, § 29).
 *
 * Фоновый проход описывается ключами `jobs`: это те же ключи, которыми сервер называет проход в
 * `track_job("ключ", …)` (`src-tauri/server/src/main.rs`). Вкладка сводит их с журналом
 * проходов; проход, о котором сервер знает, а здесь его нет, вкладка всё равно покажет
 * в конце под его ключом. Расхождение ловит и `tests/mechanisms_registry.rs`.
 */

/** Вкладка админки по её id (`TAB_GROUPS` на странице админки). */
export type AdminTabId = string;

export interface AutoMechanism {
	id: string;
	title: string;
	/** Что делает, обычными словами. */
	what: string;
	/** Как часто идёт. */
	schedule: string;
	/** Ключи проходов из `track_job`. Пусто — механизм работает не фоновым проходом. */
	jobs: string[];
	/** Где на него смотреть в админке. */
	tab?: AdminTabId;
}

export interface HandTool {
	id: string;
	title: string;
	what: string;
	/** Вкладка, где он лежит; без неё — `where` словами. */
	tab?: AdminTabId;
	where?: string;
}

export interface Script {
	title: string;
	what: string;
	/** Команда или путь. */
	run: string;
}

export interface ClaudeSkill {
	skill: string;
	title: string;
	/** Что сказать Claude, чтобы он взялся. */
	say: string;
}

