#!/usr/bin/env python3
"""Corrections of the base texts on the live site → one SQL migration.

  python3 tools/i18n/make_fixes.py                       # check, then write the file
  python3 tools/i18n/make_fixes.py --check               # check only
  python3 tools/i18n/make_fixes.py --stamp 20261105000000

Reads tools/i18n/fixes/:

  figurines_en.json        {slug: {field: {from, to}}}   English columns of `figurines`
                           (field names as in source/figurines.json: name,
                           shortText, fullDescription, material, ...)
  figurine_images_en.json  {image id: {from, to}}        `images.alt_text`
  races.json               {"update": {slug: {column: {from, to}}},
                            "delete_if_unused": [slug, ...]}   `battle_races`

and writes src-tauri/server/migrations/<stamp>_fix_texts.sql.

Every UPDATE changes a value only while it still equals `from` — the text that
was on the live site when the fix was written. A text the keeper has edited
since is never overwritten; on a database without the row nothing happens.
`updated_at` is left alone: a correction is not the keeper's edit. Running the
file twice changes nothing the second time.

A race in `delete_if_unused` is deleted only while no card, no studio race and
no other race's damage table refers to it, and while the keeper has not dressed
it (no uploaded picture in its level frames, no icon).

sqlx keeps a checksum of every applied migration: once applied, the file must
not change. Further corrections go into a NEW file with a later stamp.

Standard library only.
"""
import argparse
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from make_migration import CYRILLIC, MIGRATIONS, ROOT, SOURCE, lit, pick_tag, read_json, sql_limits  # noqa: E402

FIXES = HERE / "fixes"
DEFAULT_STAMP = "20261022000001"
UUID_RE = re.compile(r"^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$")
RACE_COLUMNS = re.compile(r"^(name|note)_(en|ru|uk|es|de|it)$")

HEAD = """-- Corrections of the base texts (English columns of the works, photo
-- descriptions, race notes) and removal of the unused duplicate race `witch`.
-- What was wrong and why: tools/i18n/fixes/README.md.
--
-- GENERATED by tools/i18n/make_fixes.py from tools/i18n/fixes/. Do not edit by hand.
--
-- Safe to run more than once and safe next to the keeper's own work:
--   * a value is replaced only while it still equals the text that was on the
--     live site when the fix was written, so a later edit by the keeper stays;
--   * rows are found by slug (works, races) or by the live site's photo id;
--     on another database they simply match nothing;
--   * `updated_at` is left alone.
--
-- sqlx keeps a checksum of every applied migration: this file must not change
-- once applied anywhere. Further fixes go into a NEW file (make_fixes.py --stamp).
"""


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--stamp", default=DEFAULT_STAMP)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--out", default=str(MIGRATIONS))
    a = ap.parse_args()
    if not re.fullmatch(r"\d{14}", a.stamp):
        sys.exit("--stamp must be YYYYMMDDHHMMSS")

    errors = []
    stmts = []  # list of lists: str | ("q", text)
    limits = sql_limits()

    def Q(s):
        return ("q", s)

    # ── works ──
    fig_src = read_json(SOURCE / "figurines.json")
    fields = fig_src["fields"]
    figs = read_json(FIXES / "figurines_en.json") or {}
    live = {i["key"]: i for i in fig_src["items"]}
    n_fig = 0
    for slug in sorted(figs):
        if slug not in live:
            errors.append(f"figurines_en.json: no work {slug!r} in source/figurines.json")
            continue
        for f in sorted(figs[slug]):
            fx = figs[slug][f]
            where = f"figurines_en.json [{slug}].{f}"
            if f not in fields:
                errors.append(f"{where}: unknown field")
                continue
            if fx.get("from") != live[slug].get(f):
                errors.append(f"{where}: `from` differs from source/figurines.json (dump newer than the fix?)")
                continue
            to = fx.get("to")
            if not isinstance(to, str) or not to.strip() or to == fx["from"]:
                errors.append(f"{where}: `to` empty or unchanged")
                continue
            if CYRILLIC.search(to):
                errors.append(f"{where}: Cyrillic in an English column")
                continue
            col = fields[f]
            stmts.append([f"-- {slug}: {f}\nUPDATE figurines\n   SET {col} = ", Q(to),
                          f"\n WHERE slug = {lit(slug)}\n   AND {col} IS NOT DISTINCT FROM ", Q(fx["from"]), ";\n"])
            n_fig += 1

    # ── photo descriptions ──
    img_src = {i["key"]: i for i in (read_json(SOURCE / "figurine_images.json") or {}).get("items", [])}
    imgs = read_json(FIXES / "figurine_images_en.json") or {}
    rows = []
    for key in sorted(imgs):
        fx = imgs[key]
        where = f"figurine_images_en.json [{key}]"
        if not UUID_RE.match(key):
            errors.append(f"{where}: key is not a UUID")
            continue
        if key not in img_src:
            errors.append(f"{where}: no such photo in source/figurine_images.json")
            continue
        if fx.get("from") != img_src[key].get("altText"):
            errors.append(f"{where}: `from` differs from source/figurine_images.json")
            continue
        to = fx.get("to")
        if not isinstance(to, str) or not to.strip() or CYRILLIC.search(to) or len(to) > 1000:
            errors.append(f"{where}: `to` empty, Cyrillic or longer than 1000")
            continue
        rows.append((key, fx["from"], to))
    if rows:
        parts = [f"-- photo descriptions: {len(rows)}\nUPDATE images AS i\n   SET alt_text = t.new_alt\n  FROM (VALUES "]
        for n, (k, old, new) in enumerate(rows):
            parts += [("" if n == 0 else ",\n       ") + f"({lit(k)}::uuid, ", Q(old), ", ", Q(new), ")"]
        parts += [") AS t(id, old_alt, new_alt)\n WHERE i.id = t.id\n   AND i.alt_text IS NOT DISTINCT FROM t.old_alt;\n"]
        stmts.append(parts)

    # ── races ──
    race_src = {i["key"]: i for i in (read_json(SOURCE / "races.json") or {}).get("items", [])}
    races = read_json(FIXES / "races.json") or {}
    n_race = 0
    for slug in sorted(races.get("update", {})):
        for col in sorted(races["update"][slug]):
            fx = races["update"][slug][col]
            where = f"races.json [{slug}].{col}"
            m = RACE_COLUMNS.match(col)
            if not m:
                errors.append(f"{where}: unknown column")
                continue
            if slug not in race_src:
                errors.append(f"{where}: no race {slug!r} in source/races.json")
                continue
            field, lang = m.groups()
            if fx.get("from") != (race_src[slug].get(field) or {}).get(lang):
                errors.append(f"{where}: `from` differs from source/races.json")
                continue
            to = fx.get("to")
            limit = limits.get(("battle_races", col), 200 if field == "note" else 60)
            if not isinstance(to, str) or not to.strip() or len(to) > limit:
                errors.append(f"{where}: `to` empty or longer than {limit}")
                continue
            if lang in ("en", "es", "de", "it") and CYRILLIC.search(to):
                errors.append(f"{where}: Cyrillic in a {lang} column")
                continue
            if lang == "uk" and re.search(r"[ыэъёЫЭЪЁ]", to):
                errors.append(f"{where}: Russian letters in a Ukrainian column")
                continue
            stmts.append([f"-- race {slug}: {col}\nUPDATE battle_races\n   SET {col} = ", Q(to),
                          f"\n WHERE slug = {lit(slug)}\n   AND {col} IS NOT DISTINCT FROM ", Q(fx["from"]), ";\n"])
            n_race += 1
    for slug in races.get("delete_if_unused", []):
        stmts.append([f"-- race {slug}: duplicate, removed only while nothing refers to it\n"
                      f"DELETE FROM battle_races AS r\n WHERE r.slug = {lit(slug)}\n"
                      f"   AND NOT EXISTS (SELECT 1 FROM battle_cards c WHERE c.race_id = r.id)\n"
                      f"   AND NOT EXISTS (SELECT 1 FROM studio_races s WHERE s.race_id = r.id)\n"
                      # Dressed by the keeper (frames per level with uploaded
                      # pictures, an icon): that is work, not a duplicate — the
                      # keeper decides, the migration does not.
                      f"   AND COALESCE(r.level_frames, '') NOT LIKE '%/static/%'\n"
                      f"   AND COALESCE(r.icon_url, '') = ''\n"
                      f"   AND NOT EXISTS (SELECT 1 FROM battle_races o\n"
                      f"                    WHERE o.id <> r.id AND COALESCE(o.race_damage, '') LIKE '%' || r.id::text || '%');\n"])

    if errors:
        print(f"ERRORS ({len(errors)}), nothing written:", file=sys.stderr)
        for e in errors:
            print("  " + e, file=sys.stderr)
        sys.exit(1)

    texts = [p[1] for st in stmts for p in st if isinstance(p, tuple)]
    tag = pick_tag("fx", texts)
    body = HEAD + f"--\n-- Texts are dollar-quoted (${tag}$ ... ${tag}$); the tag occurs in no text.\n\n" + "\n".join(
        "".join(f"${tag}${p[1]}${tag}$" if isinstance(p, tuple) else p for p in st) for st in stmts)
    path = Path(a.out) / f"{a.stamp}_fix_texts.sql"
    if not a.check:
        if path.exists() and path.read_text() != body:
            sys.exit(f"refusing to rewrite {path.name}: an applied migration must never change "
                     f"(sqlx checksums); use a new --stamp")
        path.write_text(body)
    shown = path.relative_to(ROOT) if path.is_relative_to(ROOT) else path
    print(f"{'would write' if a.check else 'wrote'} {shown}: {n_fig} work fields, {len(rows)} photo descriptions, "
          f"{n_race} race columns, {len(races.get('delete_if_unused', []))} race deletions")


if __name__ == "__main__":
    main()
